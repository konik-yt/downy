window.icon = (name, cls = "") =>
  `<svg class="ic ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${window.ICONS[name] || ""}</svg>`;

window.paintIcons = (root = document) => {
  for (const el of root.querySelectorAll("[data-icon]")) {
    if (el.dataset.painted === el.dataset.icon) continue;
    el.querySelector(":scope > svg.ic")?.remove();
    el.insertAdjacentHTML("afterbegin", window.icon(el.dataset.icon));
    el.dataset.painted = el.dataset.icon;
  }
};
